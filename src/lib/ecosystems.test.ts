import { readCargoLock, readPipfileLock, readPoetryLock, readRequirements, readUvLock, readYarnLock } from './lockfile';
import { mirrorSource } from './mirror';
import { apiSource, type Fetcher } from './osv';
import { runScan } from './scan';
import { reconcile, EMPTY_TRACKING, trackKey } from './tracking';

const versions = (r: { packages: { name: string; version: string }[] }) => r.packages.map((p) => `${p.name}@${p.version}`);
const skippedNames = (r: { skipped: { name: string }[] }) => r.skipped.map((s) => s.name);

describe('yarn.lock', () => {
  it('reads v1: one entry per header, and counts what was not resolved from the registry', () => {
    const v1 = `# THIS IS AN AUTOGENERATED FILE.
# yarn lockfile v1


"@babel/core@^7.0.0", "@babel/core@^7.29.0":
  version "7.29.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.29.0.tgz#abc"
  integrity sha512-x

lodash@^4.17.21:
  version "4.17.21"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-4.17.21.tgz#def"

mylib@file:../mylib:
  version "0.0.1"
`;
    const r = readYarnLock(v1);
    expect(r.ecosystem).toBe('npm');
    expect(versions(r)).toEqual(['@babel/core@7.29.0', 'lodash@4.17.21']);
    expect(skippedNames(r)).toEqual(['mylib']);
  });

  it('reads berry: only npm: resolutions are registry versions', () => {
    const berry = `__metadata:
  version: 8
  cacheKey: 10

"lodash@npm:^4.17.21":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
  checksum: 10/abc

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."

"left-pad@patch:left-pad@npm%3A1.3.0#./.patches/x.patch":
  version: 1.3.0
  resolution: "left-pad@patch:left-pad@npm%3A1.3.0#./.patches/x.patch"
`;
    const r = readYarnLock(berry);
    expect(versions(r)).toEqual(['lodash@4.17.21']);
    expect(skippedNames(r).sort()).toEqual(['app', 'left-pad']);
  });

  it('refuses a text that is neither yarn format', () => {
    expect(() => readYarnLock('hello')).toThrow(/NOT_A_LOCKFILE/);
  });
});

describe('Python lockfiles', () => {
  it('reads Pipfile.lock default and develop, pinned versions only', () => {
    const lock = JSON.stringify({
      _meta: {}, default: { django: { version: '==3.2.0' }, mylib: { path: '.' } },
      develop: { pytest: { version: '==7.0.0' }, tool: { git: 'https://x/y.git' } },
    });
    const r = readPipfileLock(lock);
    expect(r.ecosystem).toBe('PyPI');
    expect(versions(r)).toEqual(['django@3.2.0', 'pytest@7.0.0']);
    expect(skippedNames(r)).toEqual(['mylib', 'tool']);
  });

  it('reads poetry.lock and counts packages from git or a path', () => {
    const poetry = `[[package]]
name = "requests"
version = "2.25.0"
description = "HTTP"
optional = false

[[package]]
name = "mytool"
version = "0.1.0"

[package.source]
type = "git"
url = "https://github.com/a/mytool.git"
reference = "main"

[metadata]
lock-version = "2.0"
`;
    const r = readPoetryLock(poetry);
    expect(versions(r)).toEqual(['requests@2.25.0']);
    expect(skippedNames(r)).toEqual(['mytool']);
  });

  it('reads uv.lock: only registry sources are asked', () => {
    const uv = `version = 1

[[package]]
name = "numpy"
version = "1.21.0"
source = { registry = "https://pypi.org/simple" }

[[package]]
name = "myproject"
version = "0.1.0"
source = { editable = "." }
`;
    const r = readUvLock(uv);
    expect(versions(r)).toEqual(['numpy@1.21.0']);
    expect(skippedNames(r)).toEqual(['myproject']);
  });

  it('reads requirements.txt pins, and counts every unpinned or editable line', () => {
    const req = `# comment
Django==3.2.0  # pinned
requests[security]==2.25.0 ; python_version >= "3.8"
numpy>=1.20
flask
-r other.txt
-e git+https://github.com/a/b.git#egg=bee
--hash=sha256:abc
`;
    const r = readRequirements(req);
    expect(versions(r)).toEqual(['Django@3.2.0', 'requests@2.25.0']);
    expect(skippedNames(r).sort()).toEqual(['bee', 'flask', 'numpy']);
  });
});

