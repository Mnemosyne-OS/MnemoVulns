describe('fixFor outside SEMVER', () => {
  const django: OsvRecord = {
    id: 'PYSEC-2021-9', modified: 'm',
    affected: [{ package: { ecosystem: 'PyPI', name: 'django' }, ranges: [{ type: 'ECOSYSTEM', events: [
      { introduced: '2.2' }, { fixed: '2.2.18' }, { introduced: '3.0' }, { fixed: '3.0.12' }, { introduced: '3.1' }, { fixed: '3.1.6' },
    ] }] }],
  };

  it('orders plain PyPI releases (the record measured on 2026-10-04) and names the fix of the right interval', () => {
    expect(fixFor(django, 'Django', '3.0.5', 'PyPI')).toEqual({ kind: 'fixed', version: '3.0.12' });
    expect(fixFor(django, 'django', '2.2', 'PyPI')).toEqual({ kind: 'fixed', version: '2.2.18' });
  });

  it('says "stated in the record" for a version it cannot order, never "not stated"', () => {
    expect(fixFor(django, 'django', '3.0.5+cpu', 'PyPI')).toEqual({ kind: 'see' });
    // A pre-release is ordered (PEP 440): it gets its fixed version, not a pointer to the record.
    expect(fixFor(django, 'django', '3.0.5rc1', 'PyPI')).toEqual({ kind: 'fixed', version: '3.0.12' });
  });

  it('compares PyPI names the way PyPI does (PEP 503)', () => {
    expect(packageName('Typing_Extensions', 'PyPI')).toBe(packageName('typing-extensions', 'PyPI'));
    expect(packageName('Typing_Extensions', 'npm')).toBe('Typing_Extensions');
  });
});

describe('one scan, several ecosystems', () => {
  it('asks a Python project online even when npm reads the local database, and says so per ecosystem', async () => {
    const asked: string[] = [];
    const fetcher: Fetcher = async (url, init) => {
      if (url.endsWith('/querybatch')) {
        const { queries } = JSON.parse(String(init?.body)) as { queries: { package: { ecosystem: string } }[] };
        asked.push(...queries.map((q) => q.package.ecosystem));
        return new Response(JSON.stringify({ results: queries.map(() => ({})) }), { status: 200 });
      }
      return new Response('{}', { status: 404 });
    };
    const mirror = mirrorSource({ query: async () => ({ asOf: '2026-10-04T00:00:00Z', records: [] }) });
    const res = await runScan({
      sourceFor: (eco) => (eco === 'npm' ? mirror : apiSource(fetcher)),
      cache: { read: async () => null, write: async () => {} },
      locks: [
        { file: 'pnpm-lock.yaml', read: { kind: 'pnpm', ecosystem: 'npm', packages: [{ ecosystem: 'npm', name: 'tar', version: '7.5.21' }], skipped: [] } },
        { file: 'requirements.txt', read: { kind: 'requirements', ecosystem: 'PyPI', packages: [{ ecosystem: 'PyPI', name: 'django', version: '3.2.0' }], skipped: [] } },
      ],
    });
    expect(asked).toEqual(['PyPI']);
    expect(res.sources).toEqual([
      { ecosystem: 'npm', kind: 'mirror', asOf: '2026-10-04T00:00:00Z' },
      { ecosystem: 'PyPI', kind: 'api', asOf: null },
    ]);
    expect(res.complete).toBe(true);
  });

  it('never answers a package of another ecosystem from a mirror', async () => {
    const mirror = mirrorSource({ query: async () => ({ asOf: 'd', records: [] }) });
    const out = await mirror.hits([{ ecosystem: 'PyPI', name: 'django', version: '3.2.0' }]);
    expect(out.unasked).toHaveLength(1);
    expect(out.error).toBe('MIRROR_OTHER_ECOSYSTEM');
    const py = mirrorSource({ query: async () => ({ asOf: 'd', records: [] }) }, 'PyPI');
    expect((await py.hits([{ ecosystem: 'PyPI', name: 'django', version: '3.2.0' }])).unasked).toHaveLength(0);
  });
});

describe('tracking across ecosystems', () => {
  it('keeps two packages of the same name in two ecosystems apart, and npm keys as they were', () => {
    const t = reconcile(EMPTY_TRACKING, {
      at: 'x', lockfileComplete: true,
      findings: [{ id: 'X-1', ecosystem: 'npm', name: 'six', version: '1.0.0' }, { id: 'X-1', ecosystem: 'PyPI', name: 'six', version: '1.0.0' }],
      installed: [{ ecosystem: 'npm', name: 'six', version: '1.0.0', asked: true }, { ecosystem: 'PyPI', name: 'six', version: '1.0.0', asked: true }],
    });
    expect(t.entries).toHaveLength(2);
    expect(t.entries.find((e) => !e.ecosystem)).toBeTruthy();
    expect(trackKey('X-1', 'six')).toBe('X-1|six');
    expect(trackKey('X-1', 'six', 'PyPI')).toBe('X-1|PyPI:six');
  });

  it('does not call a Python package removed when only the npm lockfile is installed', () => {
    const before = reconcile(EMPTY_TRACKING, {
      at: 'x', lockfileComplete: true,
      findings: [{ id: 'P-1', ecosystem: 'PyPI', name: 'django', version: '3.2.0' }],
      installed: [{ ecosystem: 'PyPI', name: 'django', version: '3.2.0', asked: true }],
    });
    // The same project, scanned while its requirements.txt could not be read.
    const after = reconcile(before, { at: 'y', findings: [], installed: [], lockfileComplete: false });
    expect(after.entries[0]!.state).toBe('open');
  });
});

describe('tracking a PyPI package across lockfile spellings', () => {
  it('keeps the same entry when the lockfile changes the spelling of a name', () => {
    const before = reconcile(EMPTY_TRACKING, {
      at: 'x', lockfileComplete: true,
      findings: [{ id: 'P-1', ecosystem: 'PyPI', name: 'Django', version: '3.2.0' }],
      installed: [{ ecosystem: 'PyPI', name: 'Django', version: '3.2.0', asked: true }],
    });
    const after = reconcile(before, {
      at: 'y', lockfileComplete: true,
      findings: [{ id: 'P-1', ecosystem: 'PyPI', name: 'django', version: '3.2.0' }],
      installed: [{ ecosystem: 'PyPI', name: 'django', version: '3.2.0', asked: true }],
    });
    expect(after.entries).toHaveLength(1);
    expect(after.entries[0]).toMatchObject({ state: 'open', since: 'x' });
  });
});
